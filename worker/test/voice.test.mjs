// Run: node test/voice.test.mjs — OpenAI is mocked; no paid calls.
import assert from "node:assert/strict";
import worker from "../src/worker.js";

let tts = 0, chat = 0;
globalThis.fetch = async (url, init) => {
  if (String(url).includes("/audio/speech")) {
    tts++; const b = JSON.parse(init.body);
    assert.ok(b.voice && b.instructions, "voice + style instructions sent");
    return new Response(new Uint8Array([1, 2, 3]), { status: 200 });
  }
  if (String(url).includes("/chat/completions")) {
    chat++; const b = JSON.parse(init.body);
    assert.ok(b.messages[1].content.includes("Conversation so far"), "transcript included");
    return new Response(JSON.stringify({ choices: [{ message: { tool_calls: [{ function: { arguments: JSON.stringify({ line: "**I disagree**, Gradualist. Why wait?" }) } }] } }],
      usage: { prompt_tokens: 2000, completion_tokens: 120 } }), { status: 200 });
  }
  throw new Error("unexpected fetch " + url);
};
const env = { OPENAI_API_KEY: "test", LAB_VOICE_DEBATE_MAX_USD: "0.002" };
const post = (path, body, e = env) => worker.fetch(new Request("http://x" + path, { method: "POST", body: JSON.stringify(body) }), e);
const ctx = { conditions: { dataMonth: "2026-08", policyRate: 3.875, coreInflation: 3, unemployment: 4.1, naturalUnemployment: 4.4, gdpGrowth: 2.2 },
  members: [{ id: "classic", rule: "Taylor", initial: 4.375, final: 4.375 }, { id: "gradualist", rule: "Inertial", initial: 4.06, final: 4.2 }] };

// turn
let r = await post("/lab/voice/turn", { ctx, transcript: [{ speaker: "gradualist", text: "Let's wait." }], speakerId: "classic", addresseeId: "gradualist", debateId: "d1" });
let j = await r.json(); assert.equal(r.status, 200, JSON.stringify(j));
assert.equal(j.text, "I disagree, Gradualist. Why wait?", "markdown stripped"); assert.ok(j.spend.debateUsd > 0);
// unknown speaker rejected
r = await post("/lab/voice/turn", { ctx, speakerId: "hacker" }); assert.equal(r.status, 500);
// demo engine: free template
r = await post("/lab/voice/turn", { ctx, speakerId: "chair", addresseeId: "classic", engine: "demo", debateId: "d0" }); j = await r.json();
assert.equal(j.source, "template"); assert.equal(chat, 1);

// tts + cache + headers
r = await post("/lab/voice/tts", { text: "Hello there.", agentId: "balanced", debateId: "d2" });
assert.equal(r.status, 200); assert.equal(r.headers.get("Content-Type"), "audio/mpeg"); assert.equal(r.headers.get("X-Lab-Cached"), "false");
r = await post("/lab/voice/tts", { text: "Hello there.", agentId: "balanced", debateId: "d2" });
assert.equal(r.headers.get("X-Lab-Cached"), "true"); assert.equal(tts, 1, "cached audio reused");
// per-debate budget (0.002 USD): a long line exceeds it → 402, no API call
r = await post("/lab/voice/tts", { text: "x".repeat(800), agentId: "chair", debateId: "d3" });
assert.equal(r.status, 402); assert.equal(tts, 1);
// no key → 503
r = await post("/lab/voice/tts", { text: "Hi", agentId: "chair" }, {}); assert.equal(r.status, 503);
// word budget is passed to the model and enforced
r = await post("/lab/voice/turn", { ctx, transcript: [], speakerId: "classic", addresseeId: "gradualist", maxWords: 20, debateId: "d4" });
assert.equal(r.status, 200);
// finals: demo template, then live (mocked) — votes are never generated by the model
r = await post("/lab/voice/finals", { ctx, decision: { votes: { classic: "aye" }, text: "raise rates" }, engine: "demo" }); j = await r.json();
assert.equal(j.source, "template"); assert.ok(j.lines.classic && j.lines.chair_reason);
// config
const cfg = await (await worker.fetch(new Request("http://x/lab/voice/config"), env)).json();
assert.equal(cfg.ttsModel, "gpt-4o-mini-tts"); assert.ok(cfg.voices.chair.voice);
console.log("VOICE TESTS PASSED");
